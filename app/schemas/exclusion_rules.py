"""Schemas for exclusion rules."""

from datetime import datetime
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field


class ExclusionRuleBase(BaseModel):
    name: str
    payees: list[str] = Field(
        default_factory=list,
        description="List of counterparties or merchants to match.",
    )
    parser_ids: list[int] = Field(
        default_factory=list,
        description="If transaction is generated by any of these parser IDs, it is excluded.",
    )
    is_active: bool = True


class ExclusionRuleCreate(ExclusionRuleBase):
    pass


class ExclusionRuleUpdate(BaseModel):
    name: Optional[str] = None
    payees: Optional[list[str]] = None
    parser_ids: Optional[list[int]] = None
    is_active: Optional[bool] = None


class ExclusionRuleRead(ExclusionRuleBase):
    model_config = ConfigDict(from_attributes=True)

    id: int
    created_at: datetime
    updated_at: datetime
    mail_count: int = Field(
        0,
        ge=0,
        description="Rows in ``fetched_email_enrichments`` with this ``exclusion_rule_id``.",
    )
